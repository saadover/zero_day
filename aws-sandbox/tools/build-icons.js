// Bundles the AWS architecture icons used by js/services.js into js/icons.js.
// Usage:  npm pack aws-icons@3.3.0 && tar xzf aws-icons-3.3.0.tgz
//         node tools/build-icons.js path/to/package/icons
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = process.argv[2];
if (!src) { console.error('usage: node tools/build-icons.js <aws-icons/package/icons>'); process.exit(1); }
require(path.join(root, 'js/services.js'));
const S = globalThis.AWSSIM;
const DIRS = { s: 'architecture-service', r: 'resource', g: 'architecture-group' };
const out = {};
let missing = 0;
for (const sv of S.SERVICE_LIST) {
  const ref = sv.icon;
  if (out[ref]) continue;
  const [k, name] = ref.split(':');
  if (k === 'x') continue; // drawn by the app itself
  const file = path.join(src, DIRS[k], name + '.svg');
  if (!fs.existsSync(file)) { console.error('missing', ref, 'for', sv.id); missing++; continue; }
  let svg = fs.readFileSync(file, 'utf8')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  out[ref] = svg;
}
if (missing) process.exit(1);
const body = '/* Generated by tools/build-icons.js from the aws-icons npm package (MIT),\n' +
  ' * which redistributes the official AWS Architecture Icons. Do not edit by hand. */\n' +
  '(function (S) { S.ICONS = ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n' +
  "})(typeof window !== 'undefined' ? (window.AWSSIM = window.AWSSIM || {}) : (globalThis.AWSSIM = globalThis.AWSSIM || {}));\n";
fs.writeFileSync(path.join(root, 'js/icons.js'), body);
console.log('wrote', Object.keys(out).length, 'icons,', body.length, 'bytes');
